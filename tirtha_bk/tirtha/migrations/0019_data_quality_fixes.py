"""
One-off corrections to production rows (internal design notes).

A data migration rather than a management command because Phase 3 lands at
cutover: this has to run once, automatically, in the same ordered chain as
everything else, rather than depending on someone remembering a command.

Every fix is guarded. If the row has drifted from what was audited -- the
duplicate has acquired images, the state has already been corrected -- the
migration leaves it alone and moves on. A cutover is the wrong moment to
discover that a cleanup script assumed more than it checked.
"""

from django.db import migrations


def fix_kopeshwar_state(apps, schema_editor):
    """
    `state="Kolhapur"` -- Kolhapur is a district of Maharashtra, not a state.

    Beyond being wrong, it breaks the Overpass seeding fallback (§4), which
    widens from district to state: with both fields set to the district, the
    widened query is the narrow one again.
    """
    Site = apps.get_model("tirtha", "Site")
    for site in Site.objects.filter(state="Kolhapur", district="Kolhapur"):
        site.state = "Maharashtra"
        # verbose_id is built from country/state/district/name, so it is stale
        # the moment state changes. The historical model in a migration has no
        # custom save(), so rebuild it here -- and retire the old slug, or the
        # published URL 404s (§2.2).
        old = site.verbose_id
        site.verbose_id = (
            f"{site.country}__{site.state}__{site.district}__{site.name}"
        ).replace(" ", "_")
        site.save()
        if old and old != site.verbose_id and not old.startswith("<auto-generated"):
            SiteSlugHistory = apps.get_model("tirtha", "SiteSlugHistory")
            SiteSlugHistory.objects.get_or_create(
                slug=old, defaults={"site_id": site.pk}
            )


def remove_typo_duplicate(apps, schema_editor):
    """
    `Victorial Memorial Statue` is a typo of `Victoria Memorial`.

    Deleted only because it is genuinely empty -- no images, no contributions,
    no runs, so nothing is lost and nothing cascades. The correctly-spelled row
    holds the 49 contributed images and is left untouched.
    """
    Site = apps.get_model("tirtha", "Site")
    Image = apps.get_model("tirtha", "Image")
    for site in Site.objects.filter(name="Victorial Memorial Statue"):
        if (
            site.contributions.count() == 0
            and site.runs.count() == 0
            and Image.objects.filter(contribution__site=site).count() == 0
        ):
            site.delete()


def noop(apps, schema_editor):
    """
    Deliberately irreversible.

    Reversing would mean recreating a row that exists to be deleted, with a new
    primary key and no content. Rolling back past this migration leaves the
    duplicate absent, which is the correct state anyway.
    """


